// Writes src/engine/expansions/catalogData.ts: what the app knows of every expansion module
// before its rules load (s18, docs/EXPANSIONS.md §2b). Run after adding a module or changing its
// modes, scenarios, options, terrains or maps:   pnpm gen:catalog
// (src/engine/expansions/catalog.test.ts fails while the file is out of date.)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { catalogEntry } from '../src/engine/expansions/catalog';
import { HEADLESS } from '../src/expansions/headless';

const out = fileURLToPath(new URL('../src/engine/expansions/catalogData.ts', import.meta.url));
const entries = HEADLESS.map(([m]) => catalogEntry(m));
const source = `/**
 * GENERATED by \`pnpm gen:catalog\` (scripts/gen-catalog.ts) from the expansion modules: do not
 * edit. Every module's ids, names, modes, scenarios (map per player count), options, terrains and
 * maps, in registry order, so the app knows them before a module's rules load (s18,
 * docs/EXPANSIONS.md §2b).
 */
import type { CatalogEntry } from './types';

export const CATALOG: readonly CatalogEntry[] = ${JSON.stringify(entries)};
`;
const config = (await resolveConfig(out)) ?? {};
writeFileSync(out, await format(source, { ...config, parser: 'typescript' }));
console.log(`${out}: ${entries.length} modules`);
